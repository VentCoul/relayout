"""Generates crates/core/src/bigrams.rs: letter-pair statistics for English and
Ukrainian, used to tell real words from text typed in the wrong layout.

Usage: python3 tools/bigrams.py EN_CORPUS.txt UK_CORPUS.txt > crates/core/src/bigrams.rs

Any large plain-text samples of each language work. Only counts of letter
pairs end up in the output, never the text itself. The committed tables were
built from the English and Ukrainian UI strings shipped in macOS, collected by
tools/extract_macos_corpus.py.
"""

import math
import re
import sys

ALPHABETS = {
    "EN": "abcdefghijklmnopqrstuvwxyz",
    "UK": "абвгґдеєжзиіїйклмнопрстуфхцчшщьюя",
}
BOUNDARY = "_"
SMOOTHING = 0.5


def model(path, alphabet):
    symbols = BOUNDARY + alphabet
    index = {c: i for i, c in enumerate(symbols)}
    size = len(symbols)
    counts = [[0] * size for _ in range(size)]
    text = open(path, encoding="utf-8").read().lower()
    for word in re.findall(f"[{alphabet}]+", text):
        chain = [0] + [index[c] for c in word] + [0]
        for a, b in zip(chain, chain[1:]):
            counts[a][b] += 1
    log_p = []
    for row in counts:
        total = sum(row) + SMOOTHING * size
        log_p.append([math.log((n + SMOOTHING) / total) for n in row])
    # Average log-probability per pair over the corpus itself: the score of
    # typical text, subtracted later so the two languages compare fairly.
    pairs = sum(sum(row) for row in counts)
    average = sum(counts[a][b] * log_p[a][b] for a in range(size) for b in range(size)) / pairs
    return symbols, log_p, average, pairs


def emit(name, symbols, log_p, average, pairs):
    size = len(symbols)
    print(f"/// Built from {pairs} letter pairs.")
    print(f'pub const {name}_SYMBOLS: &str = "{symbols}";')
    print(f"pub const {name}_AVERAGE: f32 = {average:.4f};")
    print(f"#[rustfmt::skip]")
    print(f"pub const {name}_LOG_P: [[f32; {size}]; {size}] = [")
    for row in log_p:
        print("    [" + ", ".join(f"{v:.2f}" for v in row) + "],")
    print("];")
    print()


def main():
    en_path, uk_path = sys.argv[1:3]
    print("//! Generated by tools/bigrams.py. Do not edit by hand.")
    print("//!")
    print("//! Natural-log probability of each letter following another, per language.")
    print(f"//! The first symbol, `{BOUNDARY}`, marks the start and the end of a word.")
    print()
    for name, path in (("EN", en_path), ("UK", uk_path)):
        emit(name, *model(path, ALPHABETS[name]))


main()
